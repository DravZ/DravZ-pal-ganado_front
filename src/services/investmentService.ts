import { useLiveQuery } from 'dexie-react-hooks';
import { cachedFarmRecords } from './offlineRecords';
import type { HatoScope } from './hatoDataService';
import {
  centsToAmount,
  isAutoGeneratedExpenseReference,
  splitCents,
  textValue,
  toCents,
} from '../utils/finance';

export interface AnimalInvestment {
  animal_id: string;
  tag_number: string | null;
  name: string | null;
  lot_id: string | null;
  lot_name: string | null;
  acquisition_cost: number;
  assigned_costs: number;
  feeding_cost: number;
  farm_overhead: number;
  total_investment: number;
  break_even_price: number;
}

export interface FarmInvestment {
  farm_id: string;
  active_animal_count: number;
  total_investment: number;
  average_investment: number;
  animals: AnimalInvestment[];
}

interface FarmInvestmentInput {
  animals: Record<string, unknown>[];
  lots: Record<string, unknown>[];
  expenses: Record<string, unknown>[];
  allocations: Record<string, unknown>[];
  feedings: Record<string, unknown>[];
}

/**
 * Reproduce en el frontend el cálculo de inversión del backend (InvestmentService) a partir
 * de los datos guardados en el dispositivo, de modo que la inversión por animal esté
 * disponible sin conexión.
 *
 * Inversión = costo de adquisición + costos asignados (directos o prorrateados por lote)
 *   + alimentación (directa, de lote o de finca, prorrateada) + parte proporcional de los
 *   gastos de finca aún no asignados. Los gastos generados automáticamente por el backend
 *   (alimentación y adquisición de animal) se excluyen del prorrateo general para no contar
 *   dos veces. El punto mínimo de venta coincide con la inversión total.
 */
function computeFarmInvestment(farmId: string, input: FarmInvestmentInput): FarmInvestment {
  const activeAnimals = input.animals.filter((animal) => {
    const status = animal.status;
    return status === null || status === undefined || textValue(status).toLowerCase() === 'active';
  });
  const activeCount = activeAnimals.length;

  const animalsByLot = new Map<string, number>();
  for (const animal of activeAnimals) {
    const lotId = textValue(animal.lot_id);
    if (lotId) animalsByLot.set(lotId, (animalsByLot.get(lotId) ?? 0) + 1);
  }

  const expenseById = new Map<string, Record<string, unknown>>();
  for (const expense of input.expenses) {
    const id = textValue(expense.id);
    if (id) expenseById.set(id, expense);
  }

  const allocatedByExpense = new Map<string, number>();
  for (const allocation of input.allocations) {
    const expenseId = textValue(allocation.expense_id);
    if (expenseId) {
      allocatedByExpense.set(
        expenseId,
        (allocatedByExpense.get(expenseId) ?? 0) + toCents(allocation.amount),
      );
    }
  }

  let unassignedFarmTotalCents = 0;
  for (const expense of input.expenses) {
    if (isAutoGeneratedExpenseReference(expense.reference_type)) continue;
    const unassigned = toCents(expense.amount) - (allocatedByExpense.get(textValue(expense.id)) ?? 0);
    if (unassigned > 0) unassignedFarmTotalCents += unassigned;
  }

  const feedingByAnimal = new Map<string, number>();
  const feedingByLot = new Map<string, number>();
  let farmLevelFeedingCents = 0;
  for (const feeding of input.feedings) {
    const cost = toCents(feeding.cost);
    const animalId = textValue(feeding.animal_id);
    const lotId = textValue(feeding.lot_id);
    if (animalId) {
      feedingByAnimal.set(animalId, (feedingByAnimal.get(animalId) ?? 0) + cost);
    } else if (lotId) {
      feedingByLot.set(lotId, (feedingByLot.get(lotId) ?? 0) + cost);
    } else {
      farmLevelFeedingCents += cost;
    }
  }

  const allocationByAnimal = new Map<string, number>();
  const allocationByLot = new Map<string, number>();
  for (const allocation of input.allocations) {
    const expense = expenseById.get(textValue(allocation.expense_id));
    if (expense && isAutoGeneratedExpenseReference(expense.reference_type)) continue;
    const animalId = textValue(allocation.animal_id);
    const lotId = textValue(allocation.lot_id);
    if (animalId) {
      allocationByAnimal.set(
        animalId,
        (allocationByAnimal.get(animalId) ?? 0) + toCents(allocation.amount),
      );
    } else if (lotId) {
      allocationByLot.set(lotId, (allocationByLot.get(lotId) ?? 0) + toCents(allocation.amount));
    }
  }

  const lotNames = new Map<string, string>();
  for (const lot of input.lots) {
    const id = textValue(lot.id);
    if (id) lotNames.set(id, textValue(lot.name));
  }

  const overheadPerAnimalCents = splitCents(unassignedFarmTotalCents, activeCount);
  const farmFeedingPerAnimalCents = splitCents(farmLevelFeedingCents, activeCount);

  let farmTotalCents = 0;
  const animals: AnimalInvestment[] = activeAnimals.map((animal) => {
    const animalId = textValue(animal.id);
    const acquisitionCents = toCents(animal.acquisition_cost);
    const assignedCents = allocationByAnimal.get(animalId) ?? 0;
    const lotId = textValue(animal.lot_id) || null;

    let lotAssignedCents = 0;
    let lotFeedingCents = 0;
    let lotName: string | null = null;
    if (lotId) {
      const lotCount = Math.max(animalsByLot.get(lotId) ?? 1, 1);
      lotAssignedCents = splitCents(allocationByLot.get(lotId) ?? 0, lotCount);
      lotFeedingCents = splitCents(feedingByLot.get(lotId) ?? 0, lotCount);
      lotName = lotNames.get(lotId) ?? null;
    }

    const feedingCents =
      (feedingByAnimal.get(animalId) ?? 0) + lotFeedingCents + farmFeedingPerAnimalCents;
    const totalCents =
      acquisitionCents + assignedCents + lotAssignedCents + feedingCents + overheadPerAnimalCents;
    farmTotalCents += totalCents;

    return {
      animal_id: animalId,
      tag_number: textValue(animal.tag_number ?? animal.identifier_tag) || null,
      name: textValue(animal.name) || null,
      lot_id: lotId,
      lot_name: lotName,
      acquisition_cost: centsToAmount(acquisitionCents),
      assigned_costs: centsToAmount(assignedCents + lotAssignedCents),
      feeding_cost: centsToAmount(feedingCents),
      farm_overhead: centsToAmount(overheadPerAnimalCents),
      total_investment: centsToAmount(totalCents),
      break_even_price: centsToAmount(totalCents),
    };
  });

  return {
    farm_id: farmId,
    active_animal_count: activeCount,
    total_investment: centsToAmount(farmTotalCents),
    average_investment: activeCount > 0 ? centsToAmount(Math.round(farmTotalCents / activeCount)) : 0,
    animals,
  };
}

/**
 * Inversión por animal de la finca activa. El cálculo se hace con los datos locales para que
 * funcione sin conexión y se mantiene actualizado a medida que se sincronizan los cambios.
 */
export function useInvestmentSummary(scope: HatoScope | null): {
  summary: FarmInvestment | null;
  isLoading: boolean;
} {
  const summary = useLiveQuery<FarmInvestment | null>(async () => {
    if (!scope) return null;
    const [animals, lots, expenses, allocations, feedings] = await Promise.all([
      cachedFarmRecords(scope.userId, 'animals', scope.farmId),
      cachedFarmRecords(scope.userId, 'lots', scope.farmId),
      cachedFarmRecords(scope.userId, 'expenses', scope.farmId),
      cachedFarmRecords(scope.userId, 'cost_allocations', scope.farmId),
      cachedFarmRecords(scope.userId, 'feeding_records', scope.farmId),
    ]);
    return computeFarmInvestment(scope.farmId, { animals, lots, expenses, allocations, feedings });
  }, [scope?.userId, scope?.farmId]);

  return {
    summary: summary ?? null,
    isLoading: scope !== null && summary === undefined,
  };
}

export function investmentByAnimalId(summary: FarmInvestment | null): Map<string, AnimalInvestment> {
  const map = new Map<string, AnimalInvestment>();
  if (summary) {
    for (const item of summary.animals) map.set(item.animal_id, item);
  }
  return map;
}
