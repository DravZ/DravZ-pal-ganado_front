/**
 * Utilidades numéricas compartidas por los cálculos financieros que el frontend replica
 * del backend (movimientos derivados e inversión por animal).
 *
 * Se trabaja en centavos para reproducir con exactitud el redondeo HALF_UP a dos
 * decimales que usa el backend con BigDecimal.
 */

export const amountValue = (value: unknown): number => {
  const parsed = typeof value === 'string' ? Number(value) : value;
  return typeof parsed === 'number' && Number.isFinite(parsed) ? parsed : 0;
};

export const textValue = (value: unknown): string => (typeof value === 'string' ? value : '');

export const referenceKey = (referenceType: unknown, referenceId: unknown): string | null => {
  const type = textValue(referenceType).trim().toUpperCase();
  const id = textValue(referenceId).trim();
  return type && id ? `${type}:${id}` : null;
};

/** Referencias de movimientos generados automáticamente por el backend. */
const AUTO_GENERATED_REFERENCES = new Set(['FEEDING', 'ANIMAL']);

export const isAutoGeneratedExpenseReference = (referenceType: unknown): boolean =>
  AUTO_GENERATED_REFERENCES.has(textValue(referenceType).trim().toUpperCase());

export const toCents = (value: unknown): number => Math.round(amountValue(value) * 100);

/** Reproduce el `split` del backend: reparto con redondeo HALF_UP a dos decimales. */
export const splitCents = (totalCents: number, divisor: number): number =>
  divisor <= 0 || totalCents === 0 ? 0 : Math.round(totalCents / divisor);

export const centsToAmount = (cents: number): number => cents / 100;
